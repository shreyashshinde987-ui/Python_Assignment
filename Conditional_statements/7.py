'''
7. Write a program to check whether a character is a vowel or consonant.
'''
character1= input("Enter character= ")
if character1 == 'a' or character1 == 'A':
    print(f"{character1} is vowel")
elif character1 == 'e' or character1 == 'E':
    print(f"{character1} is vowel")   
elif character1 == 'i' or character1 == 'I':
    print(f"{character1} is vowel")
elif character1 == 'o' or character1 == 'O':
    print(f"{character1} is vowel")
elif character1 == 'u' or character1 == 'U':
    print(f"{character1} is vowel")             
else:
    print(f"{character1} is consonant")